KNOBS = {}
for _n, _c, _d, _k, _r, _e, _x, _seen, _conf in _RAW:
    KNOBS[_n] = {"cls": _c, "default": _d, "kind": _k, "readers": list(_r),
                 "evidence": _e, "note": _x, "defaults_seen": _seen,
                 "conflict": bool(_conf), "unverified": _e.startswith("AUTO")}
del _n, _c, _d, _k, _r, _e, _x, _seen, _conf


def get(name):
    """The knob entry, or None.  A miss is a provenance FAILURE, not a default."""
    return KNOBS.get(name)


def names():
    return sorted(KNOBS)


def cls_of(name):
    k = KNOBS.get(name)
    return k["cls"] if k else "unregistered"


_OFF = ("0", "false", "off", "no", "", "none", "disabled")
_ON = ("1", "true", "yes", "on", "y", "t")


def truthy(raw):
    """The tree's own boolean reading (webui/config.py:127-142)."""
    if raw is None:
        return False
    s = str(raw).strip().lower()
    if not s:
        return False
    if s in _ON:
        return True
    if s in _OFF:
        return False
    # a non-boolean string in a flag slot is still "on" in this tree
    return True


def normalize(name, raw):
    """A value that collapses every spelling of the same behaviour."""
    k = KNOBS.get(name) or {}
    if raw is None or str(raw).strip() == "":
        return ""
    kind = k.get("kind", "str")
    if kind == "flag":
        return "1" if truthy(raw) else "0"
    if kind == "int":
        try:
            return str(int(str(raw).strip()))
        except ValueError:
            return str(raw).strip()
    return str(raw).strip()


def arm_values(environ=None):
    """{name: normalized} over the ARM classes -- the identity an A/B must match."""
    env = os.environ if environ is None else environ
    out = {}
    for n, k in KNOBS.items():
        if k["cls"] not in ARM_CLASSES:
            continue
        raw = env.get(n)
        out[n] = normalize(n, raw if raw is not None else k["default"])
    return out


def arm_id(environ=None, n=16):
    """sha256[:n] over the ARM classes only.  Same id => provably one arm."""
    blob = json.dumps(arm_values(environ), sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(blob.encode()).hexdigest()[:n]


def registry_sha():
    blob = json.dumps({n: [k["cls"], k["default"]] for n, k in KNOBS.items()},
                      sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(blob.encode()).hexdigest()


